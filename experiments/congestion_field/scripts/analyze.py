"""Pre-registered analysis (RESULTS_PLAN.md).  Writes analysis.md and prints it.

For every arm and comparator method vs base, per (map, N) cell:
  success rates, mean SoC, mean relative improvement r = (SoC_base - SoC_new) / SoC_base on instances
  solved by both, paired bootstrap 95% CI (10,000 resamples, numpy seed 0), cell pass/fail, win/tie/loss,
  headroom (SoC_base - LB) / SoC_base, field time share.
"""
import csv
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from run import RUNS, ROOT, AGENTS, cfg_id  # noqa: E402
import json  # noqa: E402

MAPS = ["warehouse", "maze", "berlin"]


def load(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return list(csv.DictReader(f))


def boot_ci(x, n=10000, seed=0):
    rng = np.random.default_rng(seed)
    x = np.asarray(x, dtype=float)
    idx = rng.integers(0, len(x), size=(n, len(x)))
    means = x[idx].mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def cell_stats(base_rows, new_rows):
    b = {r["scen"]: r for r in base_rows}
    nw = {r["scen"]: r for r in new_rows}
    scens = sorted(set(b) | set(nw), key=int)
    ok = lambda r: r is not None and r["valid"] == "1"  # noqa: E731
    rs, win, tie, loss, both_fail = [], 0, 0, 0, 0
    soc_b, soc_n, head, fshare = [], [], [], []
    for s in scens:
        rb, rn = b.get(s), nw.get(s)
        if ok(rb):
            head.append((int(rb["soc"]) - int(rb["lb"])) / int(rb["soc"]))
        if rn is not None and rn["wall_ms"] not in ("", "0"):
            fshare.append(float(rn["field_ms"] or 0) / float(rn["wall_ms"]))
        if ok(rb) and ok(rn):
            sb, sn = int(rb["soc"]), int(rn["soc"])
            rs.append((sb - sn) / sb)
            soc_b.append(sb)
            soc_n.append(sn)
            win += sn < sb
            loss += sn > sb
            tie += sn == sb
        elif ok(rn):
            win += 1
        elif ok(rb):
            loss += 1
        else:
            both_fail += 1
    succ_b = sum(ok(b.get(s)) for s in scens) / max(1, len(scens))
    succ_n = sum(ok(nw.get(s)) for s in scens) / max(1, len(scens))
    mean_r = float(np.mean(rs)) if rs else float("nan")
    lo, hi = boot_ci(rs) if len(rs) >= 2 else (float("nan"), float("nan"))
    passed = bool(rs) and mean_r >= 0.05 and lo > 0 and succ_n >= succ_b
    return dict(n=len(scens), n_both=len(rs), succ_b=succ_b, succ_n=succ_n, mean_r=mean_r, lo=lo, hi=hi,
                passed=passed, win=win, tie=tie, loss=loss, both_fail=both_fail,
                soc_b=float(np.mean(soc_b)) if soc_b else float("nan"),
                soc_n=float(np.mean(soc_n)) if soc_n else float("nan"),
                head=float(np.mean(head)) if head else float("nan"),
                fshare=float(np.mean(fshare)) if fshare else 0.0)


def table(rows, arm, method, cfg=None):
    lines = ["| map | N | n | both solved | succ base | succ new | mean SoC base | mean SoC new | mean r | 95% CI | "
             "W/T/L | headroom | field time share | pass |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    passes = {}
    for m in MAPS:
        for n in AGENTS[arm][m]:
            br = [r for r in rows if r["method"] == "base" and r["map"] == m and r["N"] == str(n)]
            nr = [r for r in rows if r["method"] == method and r["map"] == m and r["N"] == str(n)
                  and (cfg is None or r["cfg"] == cfg)]
            if not br or not nr:
                continue
            c = cell_stats(br, nr)
            passes[(m, n)] = c["passed"]
            lines.append(
                f"| {m} | {n} | {c['n']} | {c['n_both']} | {c['succ_b']:.2f} | {c['succ_n']:.2f} | {c['soc_b']:.0f} | "
                f"{c['soc_n']:.0f} | {100 * c['mean_r']:+.2f}% | [{100 * c['lo']:+.2f}, {100 * c['hi']:+.2f}]% | "
                f"{c['win']}/{c['tie']}/{c['loss']} | {100 * c['head']:.1f}% | {100 * c['fshare']:.1f}% | "
                f"{'PASS' if c['passed'] else 'fail'} |")
    per_map = {m: sum(v for (mm, _), v in passes.items() if mm == m) for m in MAPS}
    supported = sum(1 for m in MAPS if per_map[m] >= 3) >= 2
    return "\n".join(lines), per_map, supported


def main():
    tp = json.load(open(os.path.join(ROOT, "tuned_params.json")))
    out = ["# Analysis output (generated by scripts/analyze.py)", ""]
    verdict = {}
    for arm in ("lacam3", "pibt", "eecbs"):
        test = load(os.path.join(RUNS, f"{arm}_test_{arm}.csv"))
        if not test:
            out.append(f"## {arm}: no held-out results yet\n")
            continue
        methods = ["forecast", "static", "ablA"] + (["ablB"] if arm == "eecbs" else []) + \
                  (["base2"] if arm == "lacam3" else [])
        out.append(f"## {arm} (held-out scenarios 6-25)\n")
        out.append(f"Tuned params: forecast `{tp[arm]['forecast']}`, static `{tp[arm]['static']}`\n")
        for meth in methods:
            t, per_map, sup = table(test, arm, meth)
            if meth == "forecast":
                verdict[arm] = sup
            out.append(f"### {meth} vs base\n")
            out.append(t)
            out.append(f"\nPassing cells per map: {per_map}. Pre-registered test "
                       f"{'MET' if sup else 'NOT met'} for {meth}.\n")
        # overfitting check: same table on the tuning set with the selected configs
        tune = load(os.path.join(RUNS, f"{arm}_tune_base.csv")) + load(os.path.join(RUNS, f"{arm}_tune_{arm}.csv"))
        for meth in ("forecast", "static"):
            t, per_map, sup = table(tune, arm, meth, cfg_id(tp[arm][meth]))
            out.append(f"### {meth} vs base on the TUNING set (scenarios 1-5, selected config)\n")
            out.append(t)
            out.append(f"\nPassing cells per map (tuning): {per_map}. Test {'MET' if sup else 'NOT met'} on tuning.\n")
    if verdict:
        if verdict.get("lacam3"):
            v = "SUPPORTED"
        elif any(verdict.values()):
            v = "INCONCLUSIVE (only a secondary arm passes)"
        else:
            v = "NOT SUPPORTED"
        out.append(f"## Pre-registered verdict: {v}\n\nPer arm (forecast vs base): {verdict}\n")
    text = "\n".join(out)
    with open(os.path.join(ROOT, "analysis.md"), "w") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
